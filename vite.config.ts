import { defineConfig } from "@lovable.dev/vite-tanstack-config";
import type { Plugin } from "vite";
import { legacyColorFallback } from "./src/build/legacy-colors";

/**
 * Windows 7 counters run Chrome 109, which has no color-mix(): give every translucent
 * Tailwind colour a real rgb()+alpha fallback in the built CSS (src/build/legacy-colors.ts).
 */
function legacyColors(): Plugin {
  return {
    name: "xtsy-legacy-colors",
    apply: "build",
    enforce: "post",
    generateBundle(_options, bundle) {
      for (const file of Object.values(bundle)) {
        if (file.type === "asset" && file.fileName.endsWith(".css") && typeof file.source === "string") {
          file.source = legacyColorFallback(file.source);
        }
      }
    },
  };
}

export default defineConfig({
  tanstackStart: {
    // Redirect TanStack Start's bundled server entry to src/server.ts (our SSR error wrapper).
    // nitro/vite builds from this
    server: { entry: "server" },
  },
  vite: {
    plugins: [legacyColors()],
  },
});
